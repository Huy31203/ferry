//! macOS clipboard: NSPasteboard read, write and change polling (spec §4.4).
//! NSPasteboard and NSWorkspace are thread-safe, so this runs off the main thread.

use std::path::PathBuf;
use std::sync::mpsc::Sender;
use std::thread;
use std::time::Duration;

use ferry_core::sniff::{Format, sniff};
use ferry_core::trigger::Snapshot;
use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{NSPasteboard, NSPasteboardItem, NSPasteboardWriting, NSWorkspace};
use objc2_foundation::{NSArray, NSData, NSString, NSURL};

/// Read order: the first type present wins.
const IMAGE_TYPES: [(&str, Format); 5] = [
    ("public.png", Format::Png),
    ("public.jpeg", Format::Jpeg),
    ("com.compuserve.gif", Format::Gif),
    ("org.webmproject.webp", Format::WebP),
    // sE pdf-formats (last: a screenshot also carries a TIFF beside its PNG)
    ("public.tiff", Format::Tiff),
];

/// Markers password managers and clipboard tools put on secret or throwaway content
/// (nspasteboard.org).
const CONCEALED_TYPES: [&str; 4] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
];

const FILE_URL: &str = "public.file-url";
const TEXT: &str = "public.utf8-plain-text";
const POLL: Duration = Duration::from_millis(250);

fn uti(format: Format) -> &'static str {
    // sE pdf-formats
    match format {
        Format::Tiff => return "public.tiff",
        Format::Heic => return "public.heic",
        Format::Avif => return "public.avif",
        Format::Pdf => return "com.adobe.pdf",
        _ => {}
    }
    IMAGE_TYPES
        .iter()
        .find(|(_, f)| *f == format)
        .map(|(t, _)| *t)
        .expect("every format has a pasteboard type")
}

pub fn read() -> Result<Snapshot, String> {
    Ok(read_from(&NSPasteboard::generalPasteboard()))
}

/// The change count now, to tell whether the user has copied since a snapshot.
pub fn seq() -> u64 {
    NSPasteboard::generalPasteboard().changeCount() as u64
}

fn read_from(pb: &NSPasteboard) -> Snapshot {
    // Read first: a copy made while reading then looks newer, never older.
    let seq = pb.changeCount() as u64;
    let types: Vec<String> = pb
        .types()
        .map(|types| types.iter().map(|t| t.to_string()).collect())
        .unwrap_or_default();
    let source_app = NSWorkspace::sharedWorkspace()
        .frontmostApplication()
        .and_then(|app| app.bundleIdentifier())
        .map(|id| id.to_string());
    let concealed = types.iter().any(|t| CONCEALED_TYPES.contains(&t.as_str()));
    if concealed {
        // Never read the data of a secret.
        return Snapshot {
            seq,
            concealed,
            source_app,
            ..Snapshot::default()
        };
    }
    let image = IMAGE_TYPES.iter().find_map(|(t, format)| {
        if !types.iter().any(|have| have == t) {
            return None;
        }
        let bytes = pb.dataForType(&NSString::from_str(t))?.to_vec();
        // Trust the content, not the label (R§2.4).
        (sniff(&bytes) == Some(*format)).then_some((*format, bytes))
    });
    let files = pb
        .pasteboardItems()
        .map(|items| {
            items
                .iter()
                .filter_map(|item| item.stringForType(&NSString::from_str(FILE_URL)))
                .filter_map(|url| NSURL::URLWithString(&url)?.to_file_path())
                .collect()
        })
        .unwrap_or_default();
    Snapshot {
        seq,
        image,
        from_bitmap: false,
        files,
        concealed,
        source_app,
    }
}

/// Put an image on the clipboard. Returns the new change count, so the watcher
/// can skip our own write.
pub fn write_image(format: Format, bytes: &[u8]) -> Result<u64, String> {
    write_image_to(&NSPasteboard::generalPasteboard(), format, bytes)
}

fn write_image_to(pb: &NSPasteboard, format: Format, bytes: &[u8]) -> Result<u64, String> {
    let seq = pb.clearContents();
    if !pb.setData_forType(
        Some(&NSData::with_bytes(bytes)),
        &NSString::from_str(uti(format)),
    ) {
        return Err("the clipboard refused the image".into());
    }
    Ok(seq as u64)
}

/// Put files on the clipboard, as Finder's Copy does.
pub fn write_files(paths: &[PathBuf]) -> Result<u64, String> {
    write_files_to(&NSPasteboard::generalPasteboard(), paths)
}

fn write_files_to(pb: &NSPasteboard, paths: &[PathBuf]) -> Result<u64, String> {
    let urls: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = paths
        .iter()
        .map(|p| NSURL::from_file_path(p).map(ProtocolObject::from_retained))
        .collect::<Option<_>>()
        .ok_or("not an absolute path")?;
    let seq = pb.clearContents();
    if !pb.writeObjects(&NSArray::from_retained_slice(&urls)) {
        return Err("the clipboard refused the files".into());
    }
    Ok(seq as u64)
}

/// Put files on the clipboard with each file's full path as text, one pasteboard
/// item per file ("Copy file paths").
pub fn write_paths(paths: &[PathBuf]) -> Result<u64, String> {
    write_paths_to(&NSPasteboard::generalPasteboard(), paths)
}

fn write_paths_to(pb: &NSPasteboard, paths: &[PathBuf]) -> Result<u64, String> {
    let items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> = paths
        .iter()
        .map(|p| {
            let url = NSURL::from_file_path(p)?.absoluteString()?;
            let item = NSPasteboardItem::new();
            item.setString_forType(&url, &NSString::from_str(FILE_URL));
            item.setString_forType(
                &NSString::from_str(&p.to_string_lossy()),
                &NSString::from_str(TEXT),
            );
            Some(ProtocolObject::from_retained(item))
        })
        .collect::<Option<_>>()
        .ok_or("not an absolute path")?;
    let seq = pb.clearContents();
    if !pb.writeObjects(&NSArray::from_retained_slice(&items)) {
        return Err("the clipboard refused the files".into());
    }
    Ok(seq as u64)
}

/// Put plain text on the clipboard ("Copy path").
pub fn write_text(text: &str) -> Result<u64, String> {
    write_text_to(&NSPasteboard::generalPasteboard(), text)
}

fn write_text_to(pb: &NSPasteboard, text: &str) -> Result<u64, String> {
    let seq = pb.clearContents();
    if !pb.setString_forType(&NSString::from_str(text), &NSString::from_str(TEXT)) {
        return Err("the clipboard refused the text".into());
    }
    Ok(seq as u64)
}

/// Send the change count on `tx` every time it changes. Stops when the receiver is gone.
pub fn watch(tx: Sender<u64>) {
    thread::Builder::new()
        .name("ferry-clipboard".into())
        .spawn(move || {
            let pb = NSPasteboard::generalPasteboard();
            let mut last = pb.changeCount();
            loop {
                thread::sleep(POLL);
                let now = pb.changeCount();
                if now != last {
                    last = now;
                    if tx.send(now as u64).is_err() {
                        return;
                    }
                }
            }
        })
        .expect("spawn the clipboard thread");
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A private pasteboard, so tests never touch the user's clipboard.
    struct Private(Retained<NSPasteboard>);
    impl Private {
        fn new() -> Self {
            Self(NSPasteboard::pasteboardWithUniqueName())
        }
    }
    impl Drop for Private {
        fn drop(&mut self) {
            // Not in objc2-app-kit's bindings; frees the named pasteboard server-side.
            let _: () = unsafe { objc2::msg_send![&*self.0, releaseGlobally] };
        }
    }

    const PNG: &[u8] = b"\x89PNG\r\n\x1a\n\0\0\0\rIHDR";

    #[test]
    fn an_image_round_trips_and_the_change_count_moves() {
        let pb = Private::new();
        let before = pb.0.changeCount() as u64;
        let seq = write_image_to(&pb.0, Format::Png, PNG).unwrap();
        assert!(seq > before);
        assert_eq!(pb.0.changeCount() as u64, seq);
        let snap = read_from(&pb.0);
        assert_eq!(snap.seq, seq);
        assert_eq!(snap.image, Some((Format::Png, PNG.to_vec())));
        assert!(!snap.concealed);
        assert!(snap.files.is_empty());
    }

    // sE pdf-formats
    /// A 1 x 1 grey TIFF: a header, one pixel and one IFD.
    fn tiny_tiff() -> Vec<u8> {
        let mut out = b"II*\0".to_vec();
        out.extend_from_slice(&10_u32.to_le_bytes()); // the IFD, after the pixel
        out.extend_from_slice(&[0x80, 0]); // the pixel, padded to a word
        let tags: [(u16, u16, u32); 8] = [
            (256, 3, 1), // width
            (257, 3, 1), // height
            (258, 3, 8), // bits per sample
            (259, 3, 1), // no compression
            (262, 3, 1), // black is zero
            (273, 4, 8), // the strip
            (277, 3, 1), // samples per pixel
            (279, 4, 1), // the strip's size
        ];
        out.extend_from_slice(&(tags.len() as u16).to_le_bytes());
        for (tag, kind, value) in tags {
            out.extend_from_slice(&tag.to_le_bytes());
            out.extend_from_slice(&kind.to_le_bytes());
            out.extend_from_slice(&1_u32.to_le_bytes());
            out.extend_from_slice(&value.to_le_bytes());
        }
        out.extend_from_slice(&0_u32.to_le_bytes());
        out
    }

    #[test]
    fn a_tiff_on_the_clipboard_is_read_when_nothing_better_is_there() {
        let pb = Private::new();
        let tiff = tiny_tiff();
        pb.0.clearContents();
        pb.0.setData_forType(
            Some(&NSData::with_bytes(&tiff)),
            &NSString::from_str("public.tiff"),
        );
        assert_eq!(read_from(&pb.0).image.map(|(f, _)| f), Some(Format::Tiff));
        // A PNG beside it wins.
        pb.0.setData_forType(
            Some(&NSData::with_bytes(PNG)),
            &NSString::from_str("public.png"),
        );
        assert_eq!(read_from(&pb.0).image.map(|(f, _)| f), Some(Format::Png));
    }

    #[test]
    fn a_label_that_lies_about_the_content_is_ignored() {
        let pb = Private::new();
        pb.0.clearContents();
        pb.0.setData_forType(
            Some(&NSData::with_bytes(b"not a png")),
            &NSString::from_str("public.png"),
        );
        assert_eq!(read_from(&pb.0).image, None);
    }

    #[test]
    fn concealed_content_is_flagged_and_not_read() {
        let pb = Private::new();
        write_image_to(&pb.0, Format::Png, PNG).unwrap();
        pb.0.setData_forType(
            Some(&NSData::with_bytes(b"")),
            &NSString::from_str("org.nspasteboard.ConcealedType"),
        );
        let snap = read_from(&pb.0);
        assert!(snap.concealed);
        assert_eq!(snap.image, None);
    }

    #[test]
    fn files_round_trip() {
        let pb = Private::new();
        let dir = std::env::temp_dir();
        let paths = vec![dir.join("ferry a.png"), dir.join("b.jpg")];
        write_files_to(&pb.0, &paths).unwrap();
        let snap = read_from(&pb.0);
        assert_eq!(snap.files, paths);
        assert_eq!(snap.image, None);
    }

    #[test]
    fn text_round_trips_and_the_change_count_moves() {
        let pb = Private::new();
        let before = pb.0.changeCount() as u64;
        let seq = write_text_to(&pb.0, "/Users/me/shot 1.png").unwrap();
        assert!(seq > before);
        let text = pb.0.stringForType(&NSString::from_str(TEXT)).unwrap();
        assert_eq!(text.to_string(), "/Users/me/shot 1.png");
        assert_eq!(read_from(&pb.0).image, None);
    }

    #[test]
    fn paths_go_on_as_files_with_their_text() {
        let pb = Private::new();
        let dir = std::env::temp_dir();
        let paths = vec![dir.join("ferry a.png"), dir.join("b.jpg")];
        let seq = write_paths_to(&pb.0, &paths).unwrap();
        assert_eq!(
            pb.0.changeCount() as u64,
            seq,
            "the watcher must recognise this write"
        );
        let snap = read_from(&pb.0);
        assert_eq!(snap.files, paths);
        assert_eq!(snap.image, None);
        let texts: Vec<String> =
            pb.0.pasteboardItems()
                .unwrap()
                .iter()
                .filter_map(|item| item.stringForType(&NSString::from_str(TEXT)))
                .map(|s| s.to_string())
                .collect();
        let want: Vec<String> = paths
            .iter()
            .map(|p| p.to_string_lossy().into_owned())
            .collect();
        assert_eq!(texts, want);
    }
}
